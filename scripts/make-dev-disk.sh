#!/usr/bin/env bash
# scripts/make-dev-disk.sh — build/refresh a pre-installed larch-os disk image
# on the HOST, without booting the installer in QEMU.
#
# This replicates exactly what installer/install.sh does, but writes directly to
# a raw disk image via loop devices. It exists to make OS (rootfs/squashfs)
# iteration fast: tune the OS, rebuild stages 6-7, then `--reflash` to swap the
# new initramfs.img onto partition 1 — partition 2 (/home, your --user flatpaks,
# your tweaks) is never touched, so it persists exactly like a real upgrade.
#
# Modes:
#   (default)    full install: create + partition + format + populate + seed home
#   --reflash    swap only initramfs.img + the per-machine config files on PART1;
#                leaves PART1 bootloader and PART2 /home alone (fast OS iteration)
#
# Artifacts are read from work/iso/ (produced by stage 8 of the Docker build). Run
# a normal build first (at minimum through stage 8). For OS-only changes the fast
# loop is:
#   ./docker-build.sh --stage 6    # rebuild squashfs + OS initramfs (in the container)
#   sudo ./scripts/make-dev-disk.sh --reflash
#   make test-qemu-dev
#
# Credentials are fixed for dev convenience; override via env:
#   DEV_HOSTNAME (default larch-dev)  DEV_USERNAME (larch)  DEV_PASSWORD (larch)
#
# Must run as root (loop devices, mount, mkfs).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK_DIR="$SCRIPT_DIR/work"
ISO_SRC="$WORK_DIR/iso"               # vmlinuz (populated by stage 8 of the Docker build)
ROOTFS_DIR="$WORK_DIR/rootfs"         # for /etc/skel seeding + the installer payload
OS_INITRAMFS="$WORK_DIR/initramfs.img"           # the bootable OS initramfs (stage 7)
PAYLOAD_SRC="$ROOTFS_DIR/usr/lib/larch/payload"  # bootx64.efi + loader/ staged into rootfs (stage 6)
DISK_IMG="${DEV_DISK_IMG:-$WORK_DIR/dev-disk.img}"
DISK_SIZE="${DEV_DISK_SIZE:-12G}"
OS_PART_SIZE="3GiB"

DEV_HOSTNAME="${DEV_HOSTNAME:-larch-dev}"
DEV_USERNAME="${DEV_USERNAME:-larch}"
DEV_PASSWORD="${DEV_PASSWORD:-larch}"

REFLASH=0
[ "${1:-}" = "--reflash" ] && REFLASH=1

die()  { echo "ERROR: $*" >&2; exit 1; }
info() { echo "  >> $*"; }

[ "$(id -u)" -eq 0 ] || die "Must be run as root (loop devices / mount)"

# ── Verify source artifacts ───────────────────────────────────────────────────
[ -f "$ISO_SRC/vmlinuz" ]          || die "work/iso/vmlinuz missing — run the build through stage 8"
[ -f "$OS_INITRAMFS" ]            || die "work/initramfs.img missing — run the build through stage 7"
[ -f "$PAYLOAD_SRC/bootx64.efi" ] || die "payload bootx64.efi missing — run the build through stage 6"
[ -d "$PAYLOAD_SRC/loader" ]      || die "payload loader/ missing — run the build through stage 6"

# ── Loop / mount plumbing (shared) ────────────────────────────────────────────
LOOP=""
MNT_OS="$(mktemp -d)"
MNT_HOME="$(mktemp -d)"

cleanup() {
    umount "$MNT_OS"   2>/dev/null || true
    umount "$MNT_HOME" 2>/dev/null || true
    [ -n "$LOOP" ] && losetup -d "$LOOP" 2>/dev/null || true
    rmdir "$MNT_OS" "$MNT_HOME" 2>/dev/null || true
}
trap cleanup EXIT

attach_loop() {
    LOOP="$(losetup --find --show --partscan "$DISK_IMG")"
    # wait for partition nodes to appear
    for _ in $(seq 1 15); do
        [ -b "${LOOP}p1" ] && [ -b "${LOOP}p2" ] && break
        sleep 0.3
    done
    [ -b "${LOOP}p1" ] || die "partition node ${LOOP}p1 never appeared"
}

# ── Generate per-machine config files into a tmp dir ──────────────────────────
gen_config() {
    CFG="$(mktemp -d)"
    printf '%s\n' "$DEV_HOSTNAME" > "$CFG/hostname"
    printf '127.0.0.1\tlocalhost\n127.0.1.1\t%s\n::1\tlocalhost ip6-localhost ip6-loopback\n' \
        "$DEV_HOSTNAME" > "$CFG/hosts"
    printf '%s:x:1000:1000:%s:/home/%s:/bin/bash\n' \
        "$DEV_USERNAME" "$DEV_USERNAME" "$DEV_USERNAME" > "$CFG/passwd"
    pw_hash="$(printf '%s' "$DEV_PASSWORD" | openssl passwd -6 -stdin)"
    today_days=$(( $(date +%s) / 86400 ))
    printf '%s:%s:%d:0:99999:7:::\n' "$DEV_USERNAME" "$pw_hash" "$today_days" > "$CFG/shadow"
    chmod 600 "$CFG/shadow"
    printf '%s\n' "$DEV_USERNAME" > "$CFG/username"
    {
        printf '# /etc/fstab — larch-os (generated by make-dev-disk.sh)\n'
        printf 'tmpfs\t\t\t/tmp\t\ttmpfs\tdefaults,nosuid,nodev\t\t0\t0\n'
        printf 'tmpfs\t\t\t/run\t\ttmpfs\tdefaults,nosuid,nodev\t\t0\t0\n'
        printf 'LABEL=LARCHHOME\t\t/home\t\text4\tdefaults,relatime,nofail\t0\t2\n'
    } > "$CFG/fstab"
}

# Copy generated config files into the mounted PART1 /larch-os dir.
write_config_files() {
    install -d "$MNT_OS/larch-os"
    cp "$CFG/hostname" "$CFG/hosts" "$CFG/passwd" \
       "$CFG/username" "$CFG/fstab" "$MNT_OS/larch-os/"
    cp "$CFG/shadow" "$MNT_OS/larch-os/shadow"
    chmod 640 "$MNT_OS/larch-os/shadow"
}

# ── REFLASH: swap OS initramfs + config only, keep /home ──────────────────────
if [ "$REFLASH" -eq 1 ]; then
    [ -f "$DISK_IMG" ] || die "no $DISK_IMG — run a full 'make dev-disk' first"
    info "Reflashing OS onto $DISK_IMG (partition 2 / home untouched)"
    attach_loop
    mount -t vfat "${LOOP}p1" "$MNT_OS"
    info "Swapping initramfs.img (fat image — embeds the new squashfs)"
    cp "$OS_INITRAMFS"        "$MNT_OS/larch-os/initramfs.img"
    cp "$ISO_SRC/vmlinuz"     "$MNT_OS/larch-os/vmlinuz"
    info "Refreshing bootloader config (loader.conf + entries) and EFI binary"
    cp -r "$PAYLOAD_SRC/loader/." "$MNT_OS/loader/"
    cp "$PAYLOAD_SRC/bootx64.efi" "$MNT_OS/EFI/BOOT/BOOTX64.EFI"
    gen_config
    write_config_files
    rm -rf "$CFG"
    sync
    umount "$MNT_OS"
    info "Reflash complete — boot with: make test-qemu-dev"
    exit 0
fi

# ── FULL INSTALL ──────────────────────────────────────────────────────────────
info "Creating fresh raw disk image: $DISK_IMG ($DISK_SIZE)"
rm -f "$DISK_IMG"
truncate -s "$DISK_SIZE" "$DISK_IMG"

info "Writing GPT partition table (PART1 LARCHOS $OS_PART_SIZE, PART2 LARCHHOME rest)"
printf 'label: gpt\nsize=%s, type=uefi, name=LARCHOS\ntype=linux, name=LARCHHOME\n' \
    "$OS_PART_SIZE" | sfdisk -q "$DISK_IMG"

attach_loop

info "Formatting PART1 as FAT32 (LARCHOS)"
mkfs.vfat -F 32 -n LARCHOS "${LOOP}p1" >/dev/null
info "Formatting PART2 as ext4 (LARCHHOME)"
mkfs.ext4 -q -L LARCHHOME -m 1 "${LOOP}p2"

# PART1: bootloader + kernel + OS initramfs + config
mount -t vfat "${LOOP}p1" "$MNT_OS"
info "Installing EFI binary + bootloader config"
install -d "$MNT_OS/EFI/BOOT"
cp "$PAYLOAD_SRC/bootx64.efi" "$MNT_OS/EFI/BOOT/BOOTX64.EFI"
cp -r "$PAYLOAD_SRC/loader"   "$MNT_OS/"
info "Copying kernel + OS initramfs"
install -d "$MNT_OS/larch-os"
cp "$ISO_SRC/vmlinuz"  "$MNT_OS/larch-os/vmlinuz"
cp "$OS_INITRAMFS"     "$MNT_OS/larch-os/initramfs.img"
gen_config
write_config_files
sync
umount "$MNT_OS"

# PART2: seed /home/<user> from rootfs /etc/skel (partition mounts at /home)
mount -t ext4 "${LOOP}p2" "$MNT_HOME"
info "Seeding home partition for $DEV_USERNAME"
if [ -d "$ROOTFS_DIR/etc/skel" ]; then
    mkdir -p "$MNT_HOME/$DEV_USERNAME"
    cp -a "$ROOTFS_DIR/etc/skel/." "$MNT_HOME/$DEV_USERNAME/" 2>/dev/null || true
    chown -R 1000:1000 "$MNT_HOME/$DEV_USERNAME"
    chmod 0750 "$MNT_HOME/$DEV_USERNAME"
fi
chown 0:0 "$MNT_HOME"
chmod 0755 "$MNT_HOME"
chown 0:0 "$MNT_HOME/lost+found" 2>/dev/null || true
sync
umount "$MNT_HOME"

rm -rf "$CFG"

echo ""
info "Done. Pre-installed dev disk ready: $DISK_IMG"
info "  hostname=$DEV_HOSTNAME  user=$DEV_USERNAME  password=$DEV_PASSWORD"
info "Boot it with:  make test-qemu-dev"
info "After OS edits: ./docker-build.sh --stage 6 && sudo $0 --reflash"
